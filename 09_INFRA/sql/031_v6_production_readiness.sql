CREATE OR REPLACE VIEW vw_bpu_v53_priced_v2 AS
SELECT
    b.article_code,
    b.designation,
    b.lot_code,
    b.sous_lot_code,
    b.unite,
    COALESCE(r.prix_local_fcfa, legacy.prix_local_fcfa)::numeric AS prix_local_fcfa,
    COALESCE(r.prix_import_fcfa, legacy.prix_import_fcfa)::numeric AS prix_import_fcfa,
    COALESCE(r.prix_optimise_fcfa, legacy.prix_optimise_fcfa)::numeric AS prix_optimise_fcfa,
    GREATEST(
        COALESCE(r.prix_local_fcfa, legacy.prix_local_fcfa)
        - COALESCE(r.prix_optimise_fcfa, legacy.prix_optimise_fcfa),
        0
    )::numeric AS economie_unitaire_fcfa,
    CASE
        WHEN COALESCE(r.prix_import_fcfa, legacy.prix_import_fcfa)
             < COALESCE(r.prix_local_fcfa, legacy.prix_local_fcfa)
        THEN 'IMPORT'
        ELSE 'LOCAL'
    END AS decision_import,
    b.fournisseur_local,
    b.fournisseur_import,
    b.pays_import,
    COALESCE(r.source_prix, legacy.source_prix)::varchar(255) AS source_prix,
    b.date_reference,
    COALESCE(r.niveau_confiance, legacy.niveau_confiance)::text AS niveau_confiance,
    m.price_reference_code,
    COALESCE(m.match_scope, 'LEGACY_LOT_FALLBACK')::text AS pricing_scope,
    COALESCE(m.match_confidence, 'LEGACY_017')::text AS pricing_confidence,
    legacy.coefficient_import,
    legacy.coefficient_transport,
    legacy.coefficient_douane,
    legacy.coefficient_logistique,
    legacy.coefficient_global_import,
    legacy.prix_base_local_fcfa,
    legacy.prix_base_import_fcfa,
    b.is_active
FROM dim_bpu_v53 b
JOIN vw_bpu_v53_priced legacy
  ON legacy.article_code = b.article_code
LEFT JOIN dim_article_price_mapping m
  ON m.article_code = b.article_code
 AND m.is_active = TRUE
LEFT JOIN dim_price_reference r
  ON r.reference_code = m.price_reference_code
 AND r.is_active = TRUE;

CREATE OR REPLACE VIEW vw_project_cost_summary AS
WITH direct_cost AS (
    SELECT
        SUM(c.quantite * p.prix_local_fcfa)::numeric AS capex_direct,
        SUM(c.quantite * p.prix_import_fcfa)::numeric AS capex_import,
        SUM(c.quantite * p.prix_optimise_fcfa)::numeric AS capex_optimise,
        COUNT(*) FILTER (WHERE p.pricing_scope = 'LEGACY_LOT_FALLBACK') AS fallback_legacy_lot_lines,
        SUM(c.quantite * p.prix_local_fcfa) FILTER (WHERE p.pricing_scope = 'LEGACY_LOT_FALLBACK')::numeric AS fallback_legacy_lot_capex
    FROM vw_fact_metre_financial_canonical c
    JOIN vw_bpu_v53_priced_v2 p
      ON p.article_code = c.article_code
),
rates AS (
    SELECT
        0.1100::numeric AS indirect_rate,
        0.0420::numeric AS site_installation_rate,
        0.0350::numeric AS import_logistics_rate,
        0.1200::numeric AS contingency_rate,
        1263.90::numeric AS surface_m2,
        6::numeric AS nb_appartements,
        3::numeric AS nb_niveaux
),
base AS (
    SELECT
        d.capex_direct,
        d.capex_import,
        d.capex_optimise,
        COALESCE(d.fallback_legacy_lot_lines, 0) AS fallback_legacy_lot_lines,
        COALESCE(d.fallback_legacy_lot_capex, 0) AS fallback_legacy_lot_capex,
        ROUND(d.capex_direct * r.indirect_rate, 2) AS indirect_costs,
        ROUND(d.capex_direct * r.site_installation_rate, 2) AS site_installation,
        ROUND(d.capex_direct * r.import_logistics_rate, 2) AS import_logistics,
        r.contingency_rate,
        r.surface_m2,
        r.nb_appartements,
        r.nb_niveaux
    FROM direct_cost d
    CROSS JOIN rates r
)
SELECT
    capex_direct,
    indirect_costs,
    site_installation,
    import_logistics,
    ROUND((capex_direct + indirect_costs + site_installation + import_logistics) * contingency_rate, 2) AS contingency,
    ROUND(
        (capex_direct + indirect_costs + site_installation + import_logistics)
        * (1 + contingency_rate),
        2
    ) AS total_project_cost,
    surface_m2,
    ROUND(capex_direct / NULLIF(surface_m2, 0), 2) AS capex_direct_per_m2,
    ROUND(
        ((capex_direct + indirect_costs + site_installation + import_logistics) * (1 + contingency_rate))
        / NULLIF(surface_m2, 0),
        2
    ) AS total_project_cost_per_m2,
    nb_appartements,
    ROUND(
        ((capex_direct + indirect_costs + site_installation + import_logistics) * (1 + contingency_rate))
        / NULLIF(nb_appartements, 0),
        2
    ) AS total_project_cost_per_appartement,
    nb_niveaux,
    ROUND(
        ((capex_direct + indirect_costs + site_installation + import_logistics) * (1 + contingency_rate))
        / NULLIF(nb_niveaux, 0),
        2
    ) AS total_project_cost_per_niveau,
    capex_import,
    capex_optimise,
    fallback_legacy_lot_lines,
    fallback_legacy_lot_capex,
    ROUND(100.0 * fallback_legacy_lot_capex / NULLIF(capex_direct, 0), 2) AS fallback_legacy_lot_pct
FROM base;

CREATE OR REPLACE VIEW vw_dashboard_direction_v6 AS
WITH by_lot AS (
    SELECT
        c.lot,
        SUM(c.quantite * p.prix_local_fcfa)::numeric AS capex_direct,
        COUNT(*) AS nb_lignes,
        COUNT(DISTINCT c.article_code) AS nb_articles,
        COUNT(*) FILTER (WHERE p.pricing_scope = 'LEGACY_LOT_FALLBACK') AS fallback_legacy_lot_lines,
        SUM(c.quantite * p.prix_local_fcfa) FILTER (WHERE p.pricing_scope = 'LEGACY_LOT_FALLBACK')::numeric AS fallback_legacy_lot_capex
    FROM vw_fact_metre_financial_canonical c
    JOIN vw_bpu_v53_priced_v2 p
      ON p.article_code = c.article_code
    GROUP BY c.lot
),
total AS (
    SELECT SUM(capex_direct) AS total_capex_direct
    FROM by_lot
)
SELECT
    b.lot,
    b.capex_direct,
    ROUND(100.0 * b.capex_direct / NULLIF(t.total_capex_direct, 0), 2) AS pct_capex_direct,
    b.nb_lignes,
    b.nb_articles,
    b.fallback_legacy_lot_lines,
    COALESCE(b.fallback_legacy_lot_capex, 0) AS fallback_legacy_lot_capex,
    p.capex_direct AS project_capex_direct,
    p.indirect_costs,
    p.site_installation,
    p.import_logistics,
    p.contingency,
    p.total_project_cost,
    p.total_project_cost_per_m2,
    p.total_project_cost_per_appartement,
    p.total_project_cost_per_niveau
FROM by_lot b
CROSS JOIN total t
CROSS JOIN vw_project_cost_summary p
ORDER BY b.capex_direct DESC;

CREATE OR REPLACE VIEW vw_cost_intelligence_v6 AS
SELECT
    c.lot,
    c.sous_lot,
    c.article_code,
    c.designation,
    c.unite,
    SUM(c.quantite)::numeric AS quantite,
