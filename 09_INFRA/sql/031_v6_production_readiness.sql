FROM vw_fact_metre_financial_canonical c
JOIN vw_bpu_v53_priced_v2 p
  ON p.article_code = c.article_code
GROUP BY
    c.lot,
    c.sous_lot,
    c.article_code,
    c.designation,
    c.unite;

