INSERT INTO dim_article_price_mapping (
    article_code,
    price_reference_code,
    match_scope,
    match_confidence,
    mapping_source,
    is_active
)
WITH normalized_bpu AS (
    SELECT
        b.article_code,
        b.lot_code,
        UPPER(TRIM(regexp_replace(b.designation, '[[:space:]]+-[[:space:]]+ligne DQE[[:space:]]+[0-9]+[[:space:]]*$', '', 'i'))) AS designation_norm,
        UPPER(TRIM(COALESCE(b.unite, ''))) AS unite_norm
    FROM dim_bpu_v53 b
),
ranked_matches AS (
    SELECT
        b.article_code,
        r.reference_code,
        r.scope_type,
        CASE
            WHEN r.scope_type = 'ARTICLE' THEN 'AUTO_EXACT_ARTICLE_V6'
            WHEN r.scope_type = 'FAMILY' THEN 'AUTO_FAMILY_V6'
            WHEN r.scope_type = 'UNIT' THEN 'AUTO_UNIT_V6'
            ELSE 'AUTO_LOT_V6'
        END AS match_confidence,
        ROW_NUMBER() OVER (
            PARTITION BY b.article_code
            ORDER BY
                CASE r.scope_type
                    WHEN 'ARTICLE' THEN 1
                    WHEN 'FAMILY' THEN 2
                    WHEN 'UNIT' THEN 3
                    WHEN 'LOT' THEN 4
                    ELSE 9
                END,
                r.price_priority,
                LENGTH(r.match_pattern) DESC,
                r.reference_code
        ) AS rn
    FROM normalized_bpu b
    JOIN dim_price_reference r
      ON r.is_active = TRUE
     AND r.lot_code = b.lot_code
     AND (
        (r.scope_type = 'ARTICLE'
            AND b.designation_norm = UPPER(TRIM(r.match_pattern))
            AND (r.unite IS NULL OR UPPER(TRIM(r.unite)) = b.unite_norm))
        OR
        (r.scope_type = 'FAMILY'
            AND b.designation_norm LIKE '%' || UPPER(TRIM(r.match_pattern)) || '%'
            AND (r.unite IS NULL OR UPPER(TRIM(r.unite)) = b.unite_norm))
        OR
        (r.scope_type = 'UNIT'
            AND UPPER(TRIM(r.unite)) = b.unite_norm)
        OR
        (r.scope_type = 'LOT')
     )
)
SELECT
    article_code,
    reference_code,
    scope_type,
    match_confidence,
    'AUTO_RULE_031',
    TRUE
FROM ranked_matches
WHERE rn = 1
